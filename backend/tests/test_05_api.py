"""Section F: API endpoint tests.

Uses FastAPI TestClient — no server needed.  Requires the precomputed
results file to exist (generated by test_04_precompute or precompute.py).
"""

import os
import sys
import json
import pytest
from fastapi.testclient import TestClient

BACKEND_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, BACKEND_DIR)

from main import app

client = TestClient(app)

EXPECTED_CASE_IDS = {"case_pass", "case_bad_search", "case_bad_tool", "case_bad_generation", "case_ambiguous"}


def test_get_cases_returns_200():
    resp = client.get("/api/cases")
    assert resp.status_code == 200
    data = resp.json()
    assert isinstance(data, list)
    assert len(data) == 5


def test_get_cases_has_required_fields():
    resp = client.get("/api/cases")
    data = resp.json()
    for entry in data:
        assert "id" in entry
        assert "question" in entry
        assert "is_correct" in entry
    ids = {e["id"] for e in data}
    assert ids == EXPECTED_CASE_IDS


def test_get_trace_bad_search():
    resp = client.get("/api/cases/case_bad_search/trace")
    assert resp.status_code == 200
    data = resp.json()
    assert "case_id" in data
    assert "question" in data
    assert "steps" in data
    assert "final_answer" in data
    assert "is_correct" in data
    assert data["is_correct"] is False
    for step in ["search", "tool", "answer"]:
        assert step in data["steps"], f"Missing step: {step}"
        assert "input" in data["steps"][step]
        assert "output" in data["steps"][step]


def test_get_trace_pass_returns_200():
    resp = client.get("/api/cases/case_pass/trace")

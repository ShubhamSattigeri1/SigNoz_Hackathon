def test_trace_schema_matches_spec():
    """Trace response must match the schema from the build spec."""
    resp = client.get("/api/cases/case_bad_search/trace")
    data = resp.json()
    # Schema: { case_id, question, steps: { search, tool, answer }, final_answer, is_correct }
    assert isinstance(data["case_id"], str)
    assert isinstance(data["question"], str)
    assert isinstance(data["steps"], dict)
    assert set(data["steps"].keys()) == {"search", "tool", "answer"}
    assert isinstance(data["final_answer"], str)
    assert isinstance(data["is_correct"], bool)
    for step in ["search", "tool", "answer"]:
        assert "input" in data["steps"][step]
        assert "output" in data["steps"][step]
